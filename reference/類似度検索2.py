# 1. モデル定義
class ResumeJobSimilarityEvaluator:
    def __init__(self):
        # 各モデルの初期化
        print("モデルを初期化中...")

        # BERT (cl-tohoku)
        self.bert_name = "cl-tohoku/bert-base-japanese"
        self.bert_tokenizer = AutoTokenizer.from_pretrained(self.bert_name)
        self.bert_model = AutoModel.from_pretrained(self.bert_name)

        # BERT-large
        self.bert_large_name = "cl-tohoku/bert-large-japanese-v2"
        self.bert_large_tokenizer = AutoTokenizer.from_pretrained(self.bert_large_name)
        self.bert_large_model = AutoModel.from_pretrained(self.bert_large_name)

        # Sentence Transformers
        self.st_model = SentenceTransformer('paraphrase-multilingual-mpnet-base-v2')
        self.st_model_jp = SentenceTransformer('sonoisa/sentence-bert-base-ja-mean-tokens-v2')

        # 新たに追加するモデル
        self.luke_jp_name = "studio-ousia/luke-japanese-base-lite"
        self.luke_jp_tokenizer = AutoTokenizer.from_pretrained(self.luke_jp_name)
        self.luke_jp_model = AutoModel.from_pretrained(self.luke_jp_name)

        # より最新のSentence Transformersモデル
        self.st_model_jp_new = SentenceTransformer('sonoisa/sentence-luke-japanese-base-lite')

        # デバイスの設定
        self.device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
        self.bert_model.to(self.device)
        self.bert_large_model.to(self.device)
        self.luke_jp_model.to(self.device)

        print(f"モデルの初期化が完了しました。使用デバイス: {self.device}")

    def get_bert_embedding(self, text, large=False):
        """BERTの埋め込みを取得"""
        if large:
            tokenizer = self.bert_large_tokenizer
            model = self.bert_large_model
        else:
            tokenizer = self.bert_tokenizer
            model = self.bert_model

        inputs = tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=512).to(self.device)
        with torch.no_grad():
            outputs = model(**inputs)

        # CLSトークンの埋め込みを使用
        cls_embedding = outputs.last_hidden_state[:, 0, :]
        return cls_embedding.cpu().squeeze().numpy()

    def get_bert_mean_pooling(self, text, large=False):
        """BERTの平均プーリング埋め込みを取得"""
        if large:
            tokenizer = self.bert_large_tokenizer
            model = self.bert_large_model
        else:
            tokenizer = self.bert_tokenizer
            model = self.bert_model

        inputs = tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=512).to(self.device)
        with torch.no_grad():
            outputs = model(**inputs)

        # 平均プーリング
        token_embeddings = outputs.last_hidden_state
        attention_mask = inputs['attention_mask']
        mask_expanded = attention_mask.unsqueeze(-1).expand(token_embeddings.size()).float()

        sum_embeddings = torch.sum(token_embeddings * mask_expanded, 1)
        sum_mask = mask_expanded.sum(1)
        mean_pooled = sum_embeddings / sum_mask

        return mean_pooled.cpu().squeeze().numpy()

    def get_luke_embedding(self, text):
        """LUKE日本語モデルの埋め込みを取得"""
        tokenizer = self.luke_jp_tokenizer
        model = self.luke_jp_model

        inputs = tokenizer(text, return_tensors="pt", truncation=True, padding=True, max_length=512).to(self.device)
        with torch.no_grad():
            outputs = model(**inputs)

        # CLSトークンの埋め込みを使用
        cls_embedding = outputs.last_hidden_state[:, 0, :]
        return cls_embedding.cpu().squeeze().numpy()

    def get_sentence_transformer_embedding(self, text, model_type="multilingual"):
        """Sentence Transformerの埋め込みを取得"""
        if model_type == "japanese":
            return self.st_model_jp.encode(text)
        elif model_type == "japanese_luke":
            return self.st_model_jp_new.encode(text)
        else:  # multilingual
            return self.st_model.encode(text)

    def cosine_similarity(self, vec1, vec2):
        """コサイン類似度を計算"""
        if isinstance(vec1, list):
            vec1 = np.array(vec1)
        if isinstance(vec2, list):
            vec2 = np.array(vec2)
        return np.dot(vec1, vec2) / (np.linalg.norm(vec1) * np.linalg.norm(vec2))

    def get_resume_job_similarity(self, resume_text, job_description, embedding_func):
        """職務経歴と求人の類似度を計算"""
        resume_embedding = embedding_func(resume_text)
        job_embedding = embedding_func(job_description)
        return self.cosine_similarity(resume_embedding, job_embedding)

    def get_weighted_resume_job_similarity(self, resume_text, job_description, embedding_func,
                                          important_keywords=None, keyword_weight=1.5):
        """重要キーワードに重みを付けた類似度計算"""
        # 基本の埋め込みを取得
        resume_embedding = embedding_func(resume_text)
        job_embedding = embedding_func(job_description)

        # 基本の類似度
        base_similarity = self.cosine_similarity(resume_embedding, job_embedding)

        # 重要キーワードがない場合は基本の類似度を返す
        if not important_keywords:
            return base_similarity

        # キーワードの出現回数をカウント
        resume_keyword_count = sum(1 for keyword in important_keywords if keyword.lower() in resume_text.lower())
        job_keyword_count = sum(1 for keyword in important_keywords if keyword.lower() in job_description.lower())

        # 両方のテキストに共通して出現するキーワードの数
        common_keywords = sum(1 for keyword in important_keywords
                             if keyword.lower() in resume_text.lower() and keyword.lower() in job_description.lower())

        # キーワード一致度の計算（0〜1の範囲）
        if len(important_keywords) > 0:
            keyword_match_ratio = common_keywords / len(important_keywords)
        else:
            keyword_match_ratio = 0

        # 重み付け類似度の計算
        weighted_similarity = base_similarity * (1 - keyword_weight) + keyword_match_ratio * keyword_weight

        return weighted_similarity

