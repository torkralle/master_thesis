def visualize_results(df_scores, results, timestamp):
    """評価結果の可視化"""

    # 1. モデルごとの類似度比較
    plt.figure(figsize=(14, 8))
    sns.barplot(x="model", y="similarity", hue="job_type", data=df_scores)
    plt.title("各モデルにおける類似度比較", fontsize=16)
    plt.xlabel("モデル", fontsize=14)
    plt.ylabel("類似度", fontsize=14)
    plt.xticks(rotation=45, ha='right')
    plt.legend(title="求人タイプ", labels=["マッチング求人", "非マッチング求人"])
    plt.tight_layout()
    plt.savefig(f"model_comparison_{timestamp}.png")

    # 2. モデルごとの分離度（箱ひげ図）
    plt.figure(figsize=(14, 8))
    sns.boxplot(x="model", y="similarity", hue="job_type", data=df_scores)
    plt.title("各モデルにおける類似度分布", fontsize=16)
    plt.xlabel("モデル", fontsize=14)
    plt.ylabel("類似度", fontsize=14)
    plt.xticks(rotation=45, ha='right')
    plt.legend(title="求人タイプ", labels=["マッチング求人", "非マッチング求人"])
    plt.tight_layout()
    plt.savefig(f"model_boxplot_{timestamp}.png")

    # 3. 職務経歴ごとの詳細比較
    # 特定のモデルを選択して詳細比較
    top_models = ["Sentence-BERT (Japanese)", "BERT-large (Mean Pooling)"]
    df_detail = df_scores[df_scores["model"].isin(top_models)]

    plt.figure(figsize=(14, 8))
    g = sns.catplot(
        data=df_detail, kind="bar",
        x="resume_id", y="similarity", hue="job_type", col="model",
        height=6, aspect=1.2, legend=False
    )
    g.set_axis_labels("職務経歴書ID", "類似度")
    g.set_titles("{col_name}")
    plt.legend(title="求人タイプ", labels=["マッチング求人", "非マッチング求人"])
    plt.tight_layout()
    plt.savefig(f"detail_comparison_{timestamp}.png")

    # 4. モデルの平均分離度のランキング
    model_summary = []
    for model_name, model_results in results.items():
        avg_separation = np.mean([r["separation"] for r in model_results])
        model_summary.append({"model": model_name, "avg_separation": avg_separation})

    df_summary = pd.DataFrame(model_summary).sort_values("avg_separation", ascending=False)

    plt.figure(figsize=(12, 8))
    sns.barplot(x="avg_separation", y="model", data=df_summary)
    plt.title("モデル別の平均分離度ランキング", fontsize=16)
    plt.xlabel("平均分離度", fontsize=14)
    plt.ylabel("モデル", fontsize=14)
    plt.tight_layout()
    plt.savefig(f"model_ranking_{timestamp}.png")

