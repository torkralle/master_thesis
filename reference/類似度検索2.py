def run_evaluation(use_weighted_similarity=True):
    evaluator = ResumeJobSimilarityEvaluator()

    # 評価するモデルの定義
    models = {
        "BERT (CLS)": lambda text: evaluator.get_bert_embedding(text, large=False),
        "BERT (Mean Pooling)": lambda text: evaluator.get_bert_mean_pooling(text, large=False),
        "BERT-large (CLS)": lambda text: evaluator.get_bert_embedding(text, large=True),
        "BERT-large (Mean Pooling)": lambda text: evaluator.get_bert_mean_pooling(text, large=True),
        "LUKE-japanese": lambda text: evaluator.get_luke_embedding(text),
        "Sentence-BERT (Multilingual)": lambda text: evaluator.get_sentence_transformer_embedding(text, model_type="multilingual"),
        "Sentence-BERT (Japanese)": lambda text: evaluator.get_sentence_transformer_embedding(text, model_type="japanese"),
        "Sentence-LUKE (Japanese)": lambda text: evaluator.get_sentence_transformer_embedding(text, model_type="japanese_luke"),
    }

    # 重み付き類似度計算用のモデルを追加
    if use_weighted_similarity:
        models.update({
            "Weighted BERT-large (Mean Pooling)": lambda text: evaluator.get_bert_mean_pooling(text, large=True),
            "Weighted Sentence-BERT (Japanese)": lambda text: evaluator.get_sentence_transformer_embedding(text, model_type="japanese"),
        })

    # 結果の保存用辞書
    results = {}
    all_scores = []

    # 各モデルの評価
    for model_name, embedding_func in models.items():
        print(f"\n=== {model_name} の評価 ===")
        model_results = []

        # 各評価データに対して
        for i, data in enumerate(evaluation_dataset):
            resume = data["resume"]
            matching_jobs = data["matching_jobs"]
            non_matching_jobs = data["non_matching_jobs"]

            # キーワードリストを職種に基づいて選択
            if i == 0:  # エンジニア/プログラマー
                keywords = important_tech_keywords
            elif i == 1:  # デザイナー
                keywords = important_design_keywords
            elif i == 2:  # マーケター
                keywords = important_marketing_keywords
            else:
                keywords = None

            # 類似度の計算
            matching_scores = []
            for job in matching_jobs:
                if "Weighted" in model_name and keywords:
                    similarity = evaluator.get_weighted_resume_job_similarity(
                        resume, job, embedding_func, important_keywords=keywords
                    )
                else:
                    similarity = evaluator.get_resume_job_similarity(resume, job, embedding_func)

                matching_scores.append(similarity)
                all_scores.append({
                    "model": model_name,
                    "resume_id": i,
                    "job_type": "matching",
                    "similarity": similarity
                })

            non_matching_scores = []
            for job in non_matching_jobs:
                if "Weighted" in model_name and keywords:
                    similarity = evaluator.get_weighted_resume_job_similarity(
                        resume, job, embedding_func, important_keywords=keywords
                    )
                else:
                    similarity = evaluator.get_resume_job_similarity(resume, job, embedding_func)

                non_matching_scores.append(similarity)
                all_scores.append({
                    "model": model_name,
                    "resume_id": i,
                    "job_type": "non_matching",
                    "similarity": similarity
                })

            # 平均スコアの計算
            avg_matching = np.mean(matching_scores)
            avg_non_matching = np.mean(non_matching_scores)
            separation = avg_matching - avg_non_matching

            model_results.append({
                "resume_id": i,
                "avg_matching": avg_matching,
                "avg_non_matching": avg_non_matching,
                "separation": separation,
                "matching_scores": matching_scores,
                "non_matching_scores": non_matching_scores
            })

        results[model_name] = model_results

    # 4. 結果の出力
    timestamp = datetime.datetime.now().strftime("%Y%m%d_%H%M%S")
    output_file = f"resume_job_similarity_evaluation_{timestamp}.txt"

    # 結果のデータフレーム化とビジュアライズ
    df_scores = pd.DataFrame(all_scores)

    # 評価結果の可視化
    visualize_results(df_scores, results, timestamp)

    with open(output_file, "w", encoding="utf-8") as f:
        f.write("職務経歴と求人スキルの類似度評価結果\n")
        f.write("=" * 50 + "\n\n")
        f.write(f"評価日時: {datetime.datetime.now().strftime('%Y-%m-%d %H:%M:%S')}\n\n")

        # モデルごとの集計結果
        f.write("【モデル比較サマリー】\n")
        f.write("-" * 30 + "\n")
        model_summary = []
        for model_name, model_results in results.items():
            avg_separation = np.mean([r["separation"] for r in model_results])
            f.write(f"{model_name}:\n")
            f.write(f"  平均分離度: {avg_separation:.3f}\n")
            model_summary.append({"model": model_name, "avg_separation": avg_separation})
        f.write("\n")

        # モデルのランキング
        model_ranking = sorted(model_summary, key=lambda x: x["avg_separation"], reverse=True)
        f.write("【モデルランキング】\n")
        for i, model_data in enumerate(model_ranking):
            f.write(f"{i+1}. {model_data['model']} (平均分離度: {model_data['avg_separation']:.3f})\n")
        f.write("\n")

        # 詳細な結果
        f.write("【詳細結果】\n")
        f.write("=" * 50 + "\n\n")

        for model_name, model_results in results.items():
            f.write(f"モデル: {model_name}\n")
            f.write("-" * 30 + "\n")

            for result in model_results:
                resume_id = result["resume_id"]
                f.write(f"職務経歴書 {resume_id+1}\n")
